import Foundation
import XCTest
@testable import ChronoForgeCore

final class SPC700Tests: XCTestCase {
    struct Cycle: Decodable, Equatable {
        let address: UInt16?
        let value: UInt8?
        let kind: String
        init(_ address: UInt16?, _ value: UInt8?, _ kind: String) {
            self.address = address; self.value = value; self.kind = kind
        }
        init(from decoder: Decoder) throws {
            var row = try decoder.unkeyedContainer()
            address = try row.decodeIfPresent(UInt16.self)
            value = try row.decodeIfPresent(UInt8.self)
            kind = try row.decode(String.self)
        }
    }
    struct State: Decodable {
        let pc: UInt16
        let a, x, y, sp, psw: UInt8
        let ram: [[Int]]
        var registers: SPC700.Registers { .init(pc: pc, a: a, x: x, y: y, sp: sp, psw: psw) }
    }
    struct Vector: Decodable {
        let name: String
        let initial, final: State
        let cycles: [Cycle]
    }
    final class Memory: SPC700Bus {
        var ram = [UInt8](repeating: 0xA5, count: 65536)
        var log: [Cycle] = []
        func read(_ address: UInt16) -> UInt8 {
            let value = ram[Int(address)]; log.append(Cycle(address, value, "read")); return value
        }
        func write(_ address: UInt16, _ value: UInt8) {
            ram[Int(address)] = value; log.append(Cycle(address, value, "write"))
        }
        func idle() { log.append(Cycle(nil, nil, "wait")) }
    }

    /// The fixture is sampled from upstream, not generated by this port. It is
    /// not committed publicly; tools/prepare_spc700_vectors.py regenerates it.
    func testBundledInstructionVectors() throws {
        struct Provenance: Decodable { let sha256: String }
        guard let data = try? resourceData("SPC700/vectors.json") else {
            throw XCTSkip("SPC700/vectors.json not generated: run tools/prepare_spc700_vectors.py on the pinned corpus")
        }
        let provenance = try JSONDecoder().decode(Provenance.self, from: resourceData("SPC700/provenance.json"))
        XCTAssertEqual(CTEventPack.sha256(Array(data)), provenance.sha256)
        let vectors = try JSONDecoder().decode([Vector].self, from: data)
        XCTAssertEqual(vectors.count, 256 * 8)
        try check(vectors)
    }

    /// Opt in to the entire pinned corpus. Setting an invalid path fails;
    /// absence of the variable skips only this extended check.
    func testFullInstructionCorpus() throws {
        guard let path = ProcessInfo.processInfo.environment["CHRONOFORGE_SPC700_VECTORS"] else {
            throw XCTSkip("Set CHRONOFORGE_SPC700_VECTORS for all 256,000 upstream cases")
        }
        for opcode in 0...255 {
            let file = URL(fileURLWithPath: path).appendingPathComponent(String(format: "%02x.json", opcode))
            let vectors = try JSONDecoder().decode([Vector].self, from: Data(contentsOf: file))
            XCTAssertEqual(vectors.count, 1000, file.lastPathComponent)
            try check(vectors)
        }
    }

    private func check(_ vectors: [Vector]) throws {
        let memory = Memory()
        let cpu = SPC700(bus: memory)
        for vector in vectors {
            // Unspecified bytes retain the nonzero fill or previous case's writes.
            // Only bytes explicitly read by the expected trace have defined values.
            memory.log.removeAll(keepingCapacity: true)
            for pair in vector.initial.ram { memory.ram[pair[0]] = UInt8(pair[1]) }
            cpu.restore(vector.initial.registers)
            let clocks = cpu.step()
            guard cpu.registers == vector.final.registers else {
                XCTFail("\(vector.name): expected \(vector.final.registers), got \(cpu.registers)"); return
            }
            for pair in vector.final.ram {
                guard memory.ram[pair[0]] == pair[1] else {
                    XCTFail("\(vector.name): RAM \(pair[0]) wanted \(pair[1]), got \(memory.ram[pair[0]])"); return
                }
            }
            guard clocks == vector.cycles.count, memory.log.count == clocks else {
                XCTFail("\(vector.name): wanted \(vector.cycles.count) cycles, got \(clocks)"); return
            }
            for (i, expected) in vector.cycles.enumerated() {
                let got = memory.log[i]
                guard expected.address == got.address, expected.kind == got.kind,
                      expected.value == nil || expected.value == got.value else {
                    XCTFail("\(vector.name) cycle \(i): wanted \(expected), got \(got)"); return
                }
            }
        }
    }

    func testHoldAndRestoreAndCycleBudget() {
        let memory = Memory()
        memory.ram[0x200] = 0xFF // STOP
        let state = SPC700.Registers(pc: 0x200)
        let cpu = SPC700(bus: memory, registers: state)
        XCTAssertEqual(cpu.step(), 7)
        XCTAssertTrue(cpu.stopped)
        XCTAssertEqual(cpu.step(), 0)
        XCTAssertEqual(cpu.run(cycles: 10), 10)
        XCTAssertEqual(cpu.cycles, 17)
        XCTAssertEqual(memory.log.suffix(10), Array(repeating: Cycle(nil, nil, "wait"), count: 10)[...])
        cpu.restore(state)
        XCTAssertFalse(cpu.stopped)
        XCTAssertEqual(cpu.cycles, 0)
        memory.ram[0x200] = 0x00 // NOP: two clocks, even with a one-clock budget.
        XCTAssertEqual(cpu.run(cycles: 1), 2)
        XCTAssertEqual(cpu.run(cycles: 0), 0)
        XCTAssertEqual(cpu.run(cycles: -1), 0)
    }
}
